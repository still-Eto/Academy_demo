/**
 * Writes public/img/CREDITS.md from the two files that already know the answer.
 *
 *     npm run credits
 *
 * Provenance lived in comments inside scripts/fetch-photography.mjs, which is
 * thorough and is not where anyone looks. This generates the document a client
 * actually asks for — every shipped file traced to a photograph, a page, a
 * licence and the slot it fills — without a second copy of the facts to keep in
 * step. `SOURCES` is the licence record; content/images.ts is the placement
 * record; this joins them.
 *
 * If a source stops being used by any slot it shows up here as unused, which is
 * the cheap way to notice a 1.5 MB JPEG that nothing renders.
 */

import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { SOURCES } from "./fetch-photography.mjs";
import { allImages } from "./manifest.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/* Which manifest slots each source file ends up in. One source can serve
   several: the hero frame is cropped twice, the playground frame twice. */
const slotsFor = (file) =>
  allImages.filter((i) => i.photo?.source === file).map((i) => i.id);

const rows = SOURCES.map((s) => ({ ...s, slots: slotsFor(s.file) }));
const used = rows.filter((r) => r.slots.length > 0);
const unused = rows.filter((r) => r.slots.length === 0);

const stem = (id) => id.replace(/\./g, "-");

const lines = [
  "# Photography credits",
  "",
  "<!-- Generated by `npm run credits`. Do not edit by hand — edit SOURCES in",
  "     scripts/fetch-photography.mjs, or the manifest in content/images.ts. -->",
  "",
  "Every photograph on this site is licensed for commercial use with no",
  "attribution required. This file exists anyway, because the question a real",
  "client asks is not whether attribution is required — it is *where did this",
  "come from*, and the answer should take five seconds rather than an afternoon.",
  "",
  "Nothing is hot-linked. Originals are committed under `public/photos/_source`,",
  "and the graded derivatives the site serves are written to `public/photos` by",
  "`npm run photos:build`. `npm run verify` fails the build if any external image",
  "host appears anywhere in the source tree.",
  "",
  `**${used.length} source photographs, filling ${used.reduce((n, r) => n + r.slots.length, 0)} slots.**`,
  "",
  "| Source file | Slots it fills | Photograph | Licence |",
  "| --- | --- | --- | --- |",
  ...used.map(
    (r) =>
      `| \`${r.file}\` | ${r.slots.map((s) => `\`${s}\``).join(", ")} | [Pexels](${r.page}) | ${r.licence} |`,
  ),
  "",
  "## Derivatives on disk",
  "",
  "Each slot is written at its own declared aspect ratio, in AVIF, WebP and JPEG,",
  "at every width the manifest asks for:",
  "",
  "| Slot | Ratio | Files |",
  "| --- | --- | --- |",
  ...allImages
    .filter((i) => i.photo)
    .map(
      (i) =>
        `| \`${i.id}\` | ${i.width}×${i.height} | \`/photos/${stem(i.id)}-{${i.photo.widths.join(",")}}.{avif,webp,jpg}\` |`,
    ),
  "",
  "## Not photographs",
  "",
  "| File | What it is |",
  "| --- | --- |",
  "| `/img/hero-bridgewood.svg` | Wordless block. Stands in if a re-skin ships without a hero photograph. |",
  "| `/img/rooms/*.svg`, `/img/building/*.svg` | Wordless blocks at each slot's ratio, drawn from the brand palette by `npm run placeholders`. |",
  "| `/img/map-bridgewood.svg` | Hand-drawn location map. Deliberately not an embedded map iframe — it is wrapped in a link that opens the visitor's own maps app, so no third-party script and no cookie. |",
  "| `/img/marisol-signature.svg` | Drawn mark. |",
  "",
  "The seventeen staff portrait slots have **no file at all**, by design. An empty",
  "portrait renders the person's initials — see the note on `ManagedAvatar` in",
  "`components/managed-image.tsx`. Putting a stranger's stock face under a named",
  "teacher's name, tenure and quote is the one thing no stock licence covers.",
  "",
];

if (unused.length) {
  lines.push(
    "## Fetched but unused",
    "",
    "Downloaded and committed, currently filling no slot. Either wire it up or",
    "drop it from `SOURCES` — a committed original that nothing renders is dead",
    "weight in the repository.",
    "",
    ...unused.map((r) => `- \`${r.file}\` — [Pexels](${r.page})`),
    "",
  );
}

const out = join(root, "public", "img", "CREDITS.md");
await writeFile(out, lines.join("\n"), "utf8");
console.log(
  `Wrote public/img/CREDITS.md — ${used.length} sources, ` +
    `${used.reduce((n, r) => n + r.slots.length, 0)} slots` +
    (unused.length ? `, ${unused.length} unused` : ""),
);
